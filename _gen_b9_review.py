def noul(qid, q, probs, conf, why):
    # 问题为二元/三档判定；gold.value = 概率最大档归一位置（2 档→0/1；3 档→0/0.5/1）
    v = round(probs.index(max(probs)) / (len(probs) - 1), 2)
    return ({"qid": qid, "primitive": "noul", "question": q},
            {"qid": qid, "value": v, "probabilities": probs, "confidence": conf,
             "samples": [v] * 5, "blind": "agree", "rationale": why})

def choice(qid, q, opts, probs, conf, why):
    val = opts[max(range(len(probs)), key=lambda i: probs[i])]
    return ({"qid": qid, "primitive": "choice", "question": q, "options": opts},
            {"qid": qid, "value": val, "probabilities": probs, "confidence": conf,
             "samples": [val] * 5, "blind": "agree", "rationale": why})

